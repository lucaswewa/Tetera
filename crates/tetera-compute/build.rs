//! Compiles the CUDA kernels in `kernels/` to fat binaries when the `cuda` feature is on and
//! `nvcc` is found (ADR-0010). Either way it writes `kernels.rs` into `OUT_DIR`, holding each
//! kernel's CUDA C source and, when `nvcc` compiled it, its fat binary, for the crate to
//! embed. Without `nvcc`, the crate compiles the source with NVRTC at run time instead.

use std::env;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

/// Machine code for every major architecture this toolkit supports, which any driver of its
/// major version runs, and PTX for GPUs newer than the toolkit. PTX alone would be refused by
/// a driver older than the toolkit that made it.
const ARCH: &str = "all-major";

fn main() {
    println!("cargo:rerun-if-changed=kernels");
    println!("cargo:rerun-if-env-changed=NVCC");
    let out = PathBuf::from(env::var_os("OUT_DIR").expect("cargo sets OUT_DIR"));
    let mut kernels: Vec<PathBuf> = fs::read_dir("kernels")
        .expect("the crate has a kernels folder")
        .filter_map(|entry| entry.ok().map(|e| e.path()))
        .filter(|path| path.extension().is_some_and(|ext| ext == "cu"))
        .collect();
    kernels.sort();

    let cuda = env::var_os("CARGO_FEATURE_CUDA").is_some();
    let nvcc = if cuda { find_nvcc() } else { None };
    if cuda && nvcc.is_none() {
        println!(
            "cargo:warning=nvcc wasn't found: the CUDA kernels will be compiled at run time with NVRTC"
        );
    }

    let mut generated = String::from(
        "// Generated by build.rs: each kernel's source, and its fat binary when nvcc made one.\n",
    );
    for path in &kernels {
        let stem = path
            .file_stem()
            .and_then(|s| s.to_str())
            .expect("kernel names are UTF-8");
        let name = stem.to_uppercase();
        let source = fs::canonicalize(path).expect("the kernel exists");
        generated += &format!(
            "pub const {name}_SOURCE: &str = include_str!({:?});\n",
            source.display().to_string()
        );
        let fatbin = nvcc
            .as_deref()
            .map(|nvcc| compile(nvcc, path, &out.join(format!("{stem}.fatbin"))));
        generated += &match fatbin {
            Some(fatbin) => format!(
                "pub const {name}_FATBIN: Option<&[u8]> = Some(include_bytes!({:?}));\n",
                fatbin.display().to_string()
            ),
            None => format!("pub const {name}_FATBIN: Option<&[u8]> = None;\n"),
        };
    }
    fs::write(out.join("kernels.rs"), generated).expect("OUT_DIR is writable");
}

/// `nvcc`: the one `NVCC` names, when it is set; otherwise on the path, or in CUDA's usual
/// place. `NVCC=none`, or any `NVCC` that won't run, leaves the kernels to NVRTC.
fn find_nvcc() -> Option<PathBuf> {
    let candidates = match env::var_os("NVCC") {
        Some(named) => vec![PathBuf::from(named)],
        None => vec![
            PathBuf::from("nvcc"),
            PathBuf::from("/usr/local/cuda/bin/nvcc"),
        ],
    };
    candidates.into_iter().find(|nvcc| {
        Command::new(nvcc)
            .arg("--version")
            .output()
            .is_ok_and(|o| o.status.success())
    })
}

/// Compiles `source` to `fatbin`. A kernel that `nvcc` refuses fails the build, with its
/// errors: better now than when the kernel is first launched.
fn compile(nvcc: &Path, source: &Path, fatbin: &Path) -> PathBuf {
    let output = Command::new(nvcc)
        .args(["--fatbin", &format!("-arch={ARCH}"), "-O3", "-o"])
        .arg(fatbin)
        .arg(source)
        .output()
        .expect("nvcc runs");
    if !output.status.success() {
        panic!(
            "nvcc couldn't compile {}:\n{}{}",
            source.display(),
            String::from_utf8_lossy(&output.stdout),
            String::from_utf8_lossy(&output.stderr)
        );
    }
    fatbin.to_path_buf()
}
